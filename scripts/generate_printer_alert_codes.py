#!/usr/bin/env python3
"""Pin exact Bambu code categories without copying vendor messages.
Runtime needs neither BambuStudio nor a network. Ambiguous codes stay generic.
"""
import argparse,hashlib,json
from pathlib import Path
GROUPS=[
 ('Filament runout reported',('run out','ran out','runout')),
 ('Filament cutter needs attention',('cutter',)),
 ('Temperature or heater needs attention',('temperature','heater','thermistor')),
 ('Filament feeding needs attention',('filament','extrud')),
 ('Fan needs attention',('fan',)),
 ('Movement or homing needs attention',('homing','motor','axis','leveling','levelling')),
 ('Print file or storage needs attention',('sd card','sdcard','memory card','print file','parse the file')),
 ('Build plate needs attention',('build plate','heatbed plate'))]
def main():
 ap=argparse.ArgumentParser(description=__doc__)
 ap.add_argument('--catalog-dir',type=Path,default=Path('/Applications/BambuStudio.app/Contents/Resources/hms'))
 a=ap.parse_args();root=Path(__file__).resolve().parents[1]
 catalogs=sorted(a.catalog_dir.glob('hms_en_*.json'))
 if not catalogs:raise SystemExit('No bundled English HMS catalogs found')
 matches={};sources=[]
 for p in catalogs:
  raw=p.read_bytes();d=json.loads(raw);sources.append({'file':p.name,'sha256':hashlib.sha256(raw).hexdigest(),'version':d.get('ver')});stack=[d]
  while stack:
   v=stack.pop()
   if isinstance(v,dict):
    c=str(v.get('ecode','')).upper();t=v.get('intro','')
    if len(c) in (8,16) and all(x in '0123456789ABCDEF' for x in c) and isinstance(t,str):
     label=next((title for title,words in GROUPS if any(w in t.lower() for w in words)),'')
     matches.setdefault(c,set()).add(label)
    stack.extend(v.values())
   elif isinstance(v,list):stack.extend(v)
 groups={title:[] for title,_ in GROUPS}
 for c,labels in sorted(matches.items()):
  if len(labels)==1 and next(iter(labels)):groups[next(iter(labels))].append(c)
 lines=['# Generated by scripts/generate_printer_alert_codes.py; category labels are ours.',
 '# Exact identifiers only; ambiguous/unknown codes retain a generic fallback.',
 '# Input hashes: docs/printer-alert-catalog.json.',
 'S = use "string".','L = use "list".','O = use "option".','groups = [']
 for i,(title,_) in enumerate(GROUPS):
  lines.append('  ("'+title+'", "|'+'|'.join(groups[title])+'|")'+(',' if i<len(GROUPS)-1 else '].'))
 lines.append('title code fallback = case L.find (fn group -> case group of (_, codes) -> S.contains ("|" + code + "|") codes) groups of O.Some (label, _) -> label | _ -> fallback.')
 (root/'std/printeralertcodes.fpr').write_text('\n'.join(lines)+'\n')
 provenance={'schema':1,'sources':sources,'category_counts':{k:len(v) for k,v in groups.items()},'ambiguous_codes_omitted':sum(len(v)>1 for v in matches.values()),'meaning':'Exact-code categories, not diagnoses. Unknown/ambiguous codes retain raw identifiers and official help links.','protocol_source':'https://github.com/bambulab/BambuStudio/blob/master/src/slic3r/GUI/DeviceCore/DevHMS.cpp'}
 (root/'docs/printer-alert-catalog.json').write_text(json.dumps(provenance,indent=2)+'\n')
 print('Generated',sum(map(len,groups.values())),'exact code categories')
if __name__=='__main__':main()
